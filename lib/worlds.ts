export type World = "earth" | "moon" | "mars";

export const WORLDS: readonly World[] = ["earth", "moon", "mars"] as const;

export function isWorld(value: string): value is World {
  return (WORLDS as readonly string[]).includes(value);
}

export interface WorldTextures {
  color: string;
  normal?: string;
  night?: string;
  clouds?: string;
  specular?: string;
  height?: string;
}

export interface WorldConfig {
  id: World;
  name: string;
  /** Mean radius in km (NASA fact sheets). */
  radiusKm: number;
  /** Surface gravity, m/s². */
  gravity: number;
  /** CSS custom property holding the world's identity color. */
  colorVar: string;
  hasAtmosphere: boolean;
  /** Fresnel rim color for the atmosphere shader. */
  atmosphereColor?: string;
  /** Textures per quality tier, served from /public/textures (generated by `npm run assets`). */
  textures: Record<"low" | "mid" | "high", WorldTextures>;
}

