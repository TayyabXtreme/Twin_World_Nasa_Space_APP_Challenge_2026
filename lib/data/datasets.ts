/** Headline numbers for the page, computed from the catalogue (never typed in by hand). */
export function catalogueStats(list: Dataset[] = DATASETS) {
  const downloaded = list.filter((d) => d.status === "downloaded");
  return {
    datasets: list.length,
    agencies: new Set(list.map((d) => d.agency)).size,
    worlds: new Set(list.map((d) => d.world)).size,
    downloadedCount: downloaded.length,
    downloadedBytes: downloaded.reduce((sum, d) => sum + (d.sizeBytes ?? 0), 0),
    downloading: list.filter((d) => d.status === "downloading"),
    needsAccount: list.filter((d) => d.status === "needs-account" || d.account),
  };
}

/** 604800210 → "605 MB", 1.44e9 → "1.44 GB" (decimal units, as archives report them). */
export function formatBytes(bytes: number | null): string {
  if (bytes == null) return "—";
  if (bytes >= 1e9) return `${(bytes / 1e9).toFixed(2)} GB`;
  if (bytes >= 1e6) return `${(bytes / 1e6).toFixed(bytes >= 1e8 ? 0 : 1)} MB`;
  if (bytes >= 1e3) return `${Math.round(bytes / 1e3)} KB`;
  return `${bytes} B`;
}
