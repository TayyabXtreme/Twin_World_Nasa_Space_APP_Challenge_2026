/**
 * Every dataset TwinWorlds uses or has catalogued, for the Data Lab (/data).
 *
 * Built from assets-raw/nasa/README.md, MANUAL-DOWNLOADS.md, download.log, the PDS labels, the Earth and partner
 * manifests and docs/archive/plan-v2.md §2. Sizes are bytes on disk, measured by `python -I scripts/build-datalab.py`
 * (2026-11-13, also written to public/data/datalab/manifest.json, with the PRP and Mini-RF statistics quoted
 * below). If a file is still arriving, set its `status` to "downloading" and `sizeBytes` to the full size from
 * its PDS label. When a fact is not known, the field says "unknown" rather than guessing.
 */

/** Where a dataset stands today. */
export type DatasetStatus = "downloaded" | "downloading" | "needs-account" | "live" | "catalogued";
export type Agency = "NASA" | "CSA" | "ESA" | "JAXA";
/** TwinWorlds features that read a dataset (as planned in docs/archive/plan-v2.md §4). */
export type Feature = "finder" | "moon-map" | "score" | "explore" | "compare";

export interface DatasetImage {
  src: string;
  alt: string;
  w: number;
  h: number;
}

export interface Dataset {
  id: string;
  /** Short dataset badge, e.g. "LRO Diviner · PRP" (same style as the Score's dataset badges). */
  badge: string;
  name: string;
  world: World;
  agency: Agency;
  /** Archive or programme that serves the files. */
  archive: string;
  mission: string;
  instrument: string;
  /** Product identifier as the archive writes it. */
  productId: string;
  /** What it measures, in plain words. */
  measures: string;
  resolution: string;
  coverage: string;
  /** When the observations were made. */
  period: string;
  /** Bytes on disk (downloaded), full size from the label (downloading), or null (streamed / not downloaded). */
  sizeBytes: number | null;
  sizeNote?: string;
  format: string;
  licence: string;
  credit: string;
  sourceUrl: string;
  status: DatasetStatus;
  usedBy: Feature[];
  /** Where the raw files sit in the repository (not served). */
  localPath?: string;
  preview?: DatasetImage;
  /** Extra images shown in the detail view (lazy-loaded). */
  gallery?: (DatasetImage & { caption: string })[];
  /** Limits a reader must know before trusting a comparison. */
  caveats: string[];
  /** What a free account would add, and where to get it. */
  account?: { adds: string; how: string; url: string };
}

